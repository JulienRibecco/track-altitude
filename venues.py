def normalize(s: str) -> str:
    s = s.lower().strip()
    # Strip accents
    import unicodedata
    s = "".join(c for c in unicodedata.normalize("NFD", s)
                if unicodedata.category(c) != "Mn")
    return s


_US_STATES = {
    "AL","AK","AZ","AR","CA","CO","CT","DE","FL","GA","HI","ID","IL","IN","IA",
    "KS","KY","LA","ME","MD","MA","MI","MN","MS","MO","MT","NE","NV","NH","NJ",
    "NM","NY","NC","ND","OH","OK","OR","PA","RI","SC","SD","TN","TX","UT","VT",
    "VA","WA","WV","WI","WY","DC",
}


def parse_venue(venue: str) -> tuple[str, Optional[str]]:
    """Parse 'Stadium Name, City (CTRY)' -> (city, country)."""
    venue = venue.strip()
    m = re.match(r"^(.*?)\s*\(([A-Z]{3})\)\s*$", venue)
    country = None
    if m:
        venue = m.group(1).strip()
        country = m.group(2)
    if "," in venue:
        parts = [p.strip() for p in venue.split(",")]
        # Drop trailing US state codes like "Eugene, OR"
        while len(parts) > 1 and parts[-1].upper() in _US_STATES:
            parts = parts[:-1]
        city = parts[-1]
    else:
        city = venue
    return city, country


def lookup(venue: str) -> tuple[Optional[float], str, Optional[str]]:
    """Return (elevation_m, city, country) or (None, city, country)."""
    city, country = parse_venue(venue)
    key = normalize(city)
    # Strip indoor / parenthetical markers like "(i)", "(in)"
    key = re.sub(r"\s*\([^)]*\)\s*", "", key).strip()
    # Replace dashes with spaces (Port-of-Spain → port of spain)
    key_dash = key.replace("-", " ").strip()
    for k in (key, key_dash):
        if k in CITY_ELEVATION:
            return CITY_ELEVATION[k], city, country
        if k.endswith(" city"):
            k2 = k[:-5]
            if k2 in CITY_ELEVATION:
                return CITY_ELEVATION[k2], city, country
    return None, city, country


