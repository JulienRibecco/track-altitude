_CACHE_PATH = Path(__file__).parent / "venue_cache.json"


def _load_cache() -> dict:
    if _CACHE_PATH.exists():
        return json.loads(_CACHE_PATH.read_text())
    return {}


def _save_cache(cache: dict) -> None:
    _CACHE_PATH.write_text(json.dumps(cache, indent=2, sort_keys=True))


def geocode_and_elevate(city: str, country: Optional[str] = None,
                        cache: Optional[dict] = None) -> Optional[float]:
    """Use Nominatim + Open-Meteo to look up elevation. Cached."""
    import requests
    if cache is None:
        cache = _load_cache()
    key = f"{city}|{country or ''}"
    if key in cache:
        return cache[key]
    # Geocode
    q = city + (f", {country}" if country else "")
    headers = {"User-Agent": "track-altitude-research/0.1 (research)"}
    try:
        r = requests.get(
            "https://nominatim.openstreetmap.org/search",
            params={"q": q, "format": "json", "limit": 1},
            headers=headers, timeout=20,
        )
        r.raise_for_status()
        results = r.json()
        if not results:
            cache[key] = None
            _save_cache(cache)
            return None
        lat, lon = float(results[0]["lat"]), float(results[0]["lon"])
        time.sleep(1.1)  # Nominatim politeness
        # Elevation
        e = requests.get(
            "https://api.open-meteo.com/v1/elevation",
            params={"latitude": lat, "longitude": lon}, timeout=20,
        )
        e.raise_for_status()
        elev = e.json().get("elevation", [None])[0]
        cache[key] = elev
        _save_cache(cache)
        return elev
    except Exception as ex:
        print(f"  geocode failed for {q}: {ex}")
        cache[key] = None
        _save_cache(cache)
        return None


